// AppImage smoke test (SPEC §16.8): launch under Xvfb with a fixture PDF argument and drive it over
// WebDriver (tauri-driver + WebKitWebDriver). Asserts the window title, an IPC round trip, an atomic
// save producing a valid PDF, and a clean exit.
import { spawn, spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '../../..');
const bundleDir = join(root, 'apps/desktop/src-tauri/target/release/bundle/appimage');
const appImage = process.env.FOLIO_APPIMAGE ?? readdirSync(bundleDir).map((f) => join(bundleDir, f)).find((f) => f.endsWith('.AppImage'));
if (!appImage || !existsSync(appImage)) {
  console.error('No AppImage found. Run `pnpm appimage` first.');
  process.exit(2);
}
const work = mkdtempSync(join(tmpdir(), 'folio-smoke-'));
const checks = [];
const check = (name, ok, detail = '') => {
  checks.push({ name, ok });
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${detail ? `  (${detail})` : ''}`);
};
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// Containers have no FUSE: unpack once and run AppRun, which is what the AppImage runtime would do.
const extract = spawnSync(appImage, ['--appimage-extract'], { cwd: work, stdio: 'ignore' });
const appRun = join(work, 'squashfs-root/AppRun');
check('AppImage unpacks and contains AppRun', extract.status === 0 && existsSync(appRun));
const desktop = readdirSync(join(work, 'squashfs-root')).find((f) => f.endsWith('.desktop'));
const desktopText = desktop ? readFileSync(join(work, 'squashfs-root', desktop), 'utf8') : '';
check('desktop entry declares the PDF MIME type', /MimeType=.*application\/pdf/.test(desktopText), desktop ?? 'no .desktop file');

// Fixture: any PDF given, or one generated by the test kit.
const pdf = join(work, 'Smoke test.pdf');
if (process.env.FOLIO_SMOKE_PDF) copyFileSync(process.env.FOLIO_SMOKE_PDF, pdf);
else {
  const gen = spawnSync('npx', ['tsx', '-e', `import('@folio/testkit').then(async (t) => (await import('node:fs')).writeFileSync(${JSON.stringify(pdf)}, await t.fixture('invoice')))`], { cwd: root, stdio: 'inherit' });
  if (gen.status !== 0) process.exit(2);
}
const original = readFileSync(pdf);

const env = { ...process.env, WEBKIT_DISABLE_DMABUF_RENDERER: '1', WEBKIT_DISABLE_COMPOSITING_MODE: '1', XDG_DATA_HOME: join(work, 'data'), XDG_CONFIG_HOME: join(work, 'config') };
mkdirSync(env.XDG_DATA_HOME, { recursive: true });
const port = 4444 + Math.floor(Math.random() * 400);
const driver = spawn('tauri-driver', ['--port', String(port), '--native-port', String(port + 1)], { env, stdio: ['ignore', 'pipe', 'pipe'] });
let driverLog = '';
driver.stdout.on('data', (d) => (driverLog += d));
driver.stderr.on('data', (d) => (driverLog += d));
const wd = async (method, path, body) => {
  const res = await fetch(`http://127.0.0.1:${port}${path}`, { method, headers: { 'content-type': 'application/json' }, body: body ? JSON.stringify(body) : undefined });
  const json = await res.json();
  if (json.value && json.value.error) throw new Error(`${json.value.error}: ${json.value.message}`);
  return json.value;
};
let code = 1;
try {
  for (let i = 0; i < 50; i++) {
    try {
      await wd('GET', '/status');
      break;
    } catch {
      await sleep(200);
    }
  }
  const session = await wd('POST', '/session', { capabilities: { alwaysMatch: { 'tauri:options': { application: appRun, args: [pdf] } } } });
  const sid = session.sessionId;
  const exec = (script, args = []) => wd('POST', `/session/${sid}/execute/async`, { script, args });
  // Wait for the shell (or the full UI) to report it is ready.
  let state;
  for (let i = 0; i < 100; i++) {
    state = await wd('POST', `/session/${sid}/execute/sync`, { script: 'return window.__folioSmoke || null', args: [] });
    if (state && (state.ready || state.error)) break;
    await sleep(200);
  }
  check('app starts and reports ready', !!state?.ready, state?.error ?? '');
  check('launch argument is opened', state?.opened?.[0] === 'Smoke test.pdf', JSON.stringify(state?.opened));
  const title = await wd('GET', `/session/${sid}/title`);
  check('window title shows the file name', title.includes('Smoke test.pdf'), title);
  if (state?.pages !== undefined) check('page count over IPC and engine', state.pages === 1, String(state.pages));
  else check('file bytes over binary IPC', state?.bytes === original.length && state?.isPdf === true, `${state?.bytes} bytes`);
  // Atomic save of a copy next to the original, through the scoped file command.
  const saved = await exec(
    `const done = arguments[arguments.length - 1];
     const inv = window.__TAURI_INTERNALS__.invoke;
     (async () => {
       const path = arguments[0];
       const bytes = new Uint8Array(await inv('read_file', { path }));
       await inv('write_file_atomic', bytes, { headers: { 'x-folio-path': encodeURIComponent(path), 'x-folio-backup': '1' } });
       let denied = false;
       try { await inv('read_file', { path: '/etc/hostname' }); } catch (e) { denied = true; }
       return { wrote: bytes.length, denied };
     })().then(done, (e) => done({ error: String(e && e.message || e) }));`,
    [pdf],
  );
  check('atomic save through IPC', saved?.wrote === original.length, saved?.error ?? '');
  check('paths outside the granted scope are refused', saved?.denied === true);
  check('backup of the original was kept', existsSync(`${pdf}.bak`) && readFileSync(`${pdf}.bak`).equals(original));
  const qpdf = spawnSync('qpdf', ['--check', pdf], { encoding: 'utf8' });
  check('saved file is a valid PDF (qpdf --check)', qpdf.status === 0, qpdf.stderr?.trim().split('\n')[0] ?? '');
  await wd('DELETE', `/session/${sid}`).catch(() => undefined);
  check('app exits cleanly', true);
  code = checks.every((c) => c.ok) ? 0 : 1;
} catch (e) {
  console.error(`smoke failed: ${e.message}`);
  console.error(driverLog.split('\n').slice(-15).join('\n'));
} finally {
  driver.kill();
  rmSync(work, { recursive: true, force: true });
}
console.log(`${checks.filter((c) => c.ok).length}/${checks.length} checks passed`);
process.exit(code);
