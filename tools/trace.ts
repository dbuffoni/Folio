// Traceability matrix (SPEC §16.4): links every Release 1 requirement to the tests tagged with its id.
// Usage: pnpm trace [-- --phase P3] [--no-write]. Exits 1 when a requirement in scope has no test.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PHASES } from './phases.ts';

const root = fileURLToPath(new URL('..', import.meta.url));

export interface Requirement {
  id: string;
  text: string;
  priority: string;
}

/** Requirement rows of the SPEC tables that are in Release 1 scope. */
export function parseRequirements(spec: string): { inScope: Requirement[]; deferred: string[] } {
  const all: Requirement[] = [];
  for (const line of spec.split('\n')) {
    const m = /^\|\s*(FR-[A-Z]+-\d+)\s*\|(.*)\|\s*([^|]*?)\s*\|\s*$/.exec(line);
    if (m) all.push({ id: m[1]!, text: m[2]!.trim(), priority: m[3]!.trim() });
  }
  // §17.0 lists features moved out of Release 1 after the tables were written; it wins over the table.
  const start = spec.indexOf('### 17.0');
  const end = spec.indexOf('### 17.1');
  const deferredIds = new Set<string>();
  for (const m of spec.slice(start, end).replace(/\(was in [^)]*\)/g, '').matchAll(/FR-([A-Z]+)-(\d+)(?:…(\d+))?/g)) {
    const from = Number(m[2]);
    const to = m[3] ? Number(m[3]) : from;
    for (let n = from; n <= to; n++) deferredIds.add(`FR-${m[1]}-${String(n).padStart(2, '0')}`);
  }
  const inScope = all.filter((r) => !/Post-R1/.test(r.priority) && r.priority !== '—' && !deferredIds.has(r.id));
  const deferred = all.filter((r) => !inScope.includes(r)).map((r) => r.id);
  return { inScope, deferred };
}

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    if (['node_modules', 'target', 'build', 'dist', '.svelte-kit', 'gen', '.git'].includes(name)) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(test|spec)\.ts$/.test(name) || /engine-suite\.ts$/.test(name)) out.push(p);
  }
  return out;
}

/** id → test locations ("file › title"). */
export function scanTests(dirs: string[]): Map<string, string[]> {
  const found = new Map<string, string[]>();
  for (const dir of dirs) {
    for (const file of walk(join(root, dir))) {
      const text = readFileSync(file, 'utf8');
      for (const m of text.matchAll(/(?:it|test|describe)(?:\.each\([^)]*\))?\(\s*(['"`])((?:\\.|(?!\1).)*)\1/g)) {
        for (const tag of m[2]!.matchAll(/@(FR-[A-Z]+-\d+)/g)) {
          const list = found.get(tag[1]!) ?? [];
          list.push(`${relative(root, file)} › ${m[2]!.replace(/\s*@FR-[A-Z]+-\d+/g, '').trim()}`);
          found.set(tag[1]!, list);
        }
      }
    }
  }
  return found;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const args = process.argv.slice(2);
  const phase = args.includes('--phase') ? args[args.indexOf('--phase') + 1] : undefined;
  const { inScope, deferred } = parseRequirements(readFileSync(join(root, 'SPEC.md'), 'utf8'));
  const tests = scanTests(['packages', 'tests', 'apps', 'tools']);
  const scope = phase ? new Set(PHASES[phase] ?? []) : undefined;
  if (phase && !PHASES[phase]) {
    console.error(`Unknown phase ${phase}. Known: ${Object.keys(PHASES).join(', ')}`);
    process.exit(2);
  }
  const unknownTags = [...tests.keys()].filter((id) => !inScope.some((r) => r.id === id));
  const missing = inScope.filter((r) => !tests.has(r.id) && (!scope || scope.has(r.id)));
  const lines = [
    '# Traceability matrix',
    '',
    `Generated by \`pnpm trace\`. ${inScope.length} Release 1 requirements, ${inScope.filter((r) => tests.has(r.id)).length} covered by at least one test, ${deferred.length} deferred (Post-R1).`,
    '',
    '| Requirement | Pri | Tests | Where |',
    '|---|---|---|---|',
    ...inScope.map((r) => {
      const t = tests.get(r.id) ?? [];
      const files = [...new Set(t.map((x) => x.split(' › ')[0]))];
      return `| ${r.id} | ${r.priority} | ${t.length || '**none**'} | ${files.map((f) => `\`${f}\``).join('<br>')} |`;
    }),
    '',
    `Deferred: ${deferred.join(', ')}`,
    '',
  ];
  if (!args.includes('--no-write')) writeFileSync(join(root, 'docs/traceability.md'), lines.join('\n'));
  if (unknownTags.length) console.warn(`Tags that are not Release 1 requirements: ${unknownTags.join(', ')}`);
  console.log(`${inScope.length - inScope.filter((r) => !tests.has(r.id)).length}/${inScope.length} Release 1 requirements have tests${phase ? ` (checking phase ${phase})` : ''}.`);
  if (missing.length) {
    console.error(`Untested requirements:\n${missing.map((r) => `  ${r.id} (${r.priority}) ${r.text.slice(0, 90)}`).join('\n')}`);
    process.exit(1);
  }
}
