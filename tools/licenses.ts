// Licence review of everything that ships (SPEC §18): fails on a licence that is not known to be
// compatible with GPL-3.0-or-later and writes THIRD-PARTY-NOTICES.md.
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const ALLOWED = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'Apache-2.0', 'MPL-2.0', 'Zlib', 'Unlicense', 'CC0-1.0', 'BlueOak-1.0.0', 'Unicode-3.0', 'Unicode-DFS-2016', 'OFL-1.1', 'GPL-3.0-or-later', 'LGPL-3.0-or-later', 'BSL-1.0', 'CDLA-Permissive-2.0']);
/** SPDX expression is fine when every alternative of an OR, or every part of an AND, is allowed. */
function ok(expr: string): boolean {
  const e = expr.replace(/[()]/g, '').trim();
  if (/ OR /.test(e)) return e.split(' OR ').some(ok);
  if (/ AND /.test(e)) return e.split(' AND ').every(ok);
  if (e.includes('/')) return e.split('/').some(ok); // Cargo's legacy "MIT/Apache-2.0"
  return ALLOWED.has(e.replace(/ WITH .*/, ''));
}

interface Row {
  name: string;
  version: string;
  license: string;
  source: 'npm' | 'cargo' | 'bundled';
}
const rows: Row[] = [];

const npm = JSON.parse(execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], { cwd: root, encoding: 'utf8', maxBuffer: 64 << 20 })) as Record<string, Array<{ name: string; versions?: string[]; version?: string }>>;
for (const [license, pkgs] of Object.entries(npm)) for (const p of pkgs) rows.push({ name: p.name, version: (p.versions ?? [p.version ?? '']).join(', '), license, source: 'npm' });

const manifest = join(root, 'apps/desktop/src-tauri/Cargo.toml');
if (existsSync(manifest)) {
  try {
    const meta = JSON.parse(execFileSync('cargo', ['metadata', '--format-version', '1', '--manifest-path', manifest], { encoding: 'utf8', maxBuffer: 256 << 20 })) as { packages: Array<{ name: string; version: string; license: string | null; source: string | null }> };
    for (const p of meta.packages) if (p.source) rows.push({ name: p.name, version: p.version, license: p.license ?? 'UNKNOWN', source: 'cargo' });
  } catch {
    console.warn('licenses: cargo is not available, Rust crates were not checked');
  }
}

rows.push({ name: 'PDFium (via @embedpdf/pdfium)', version: 'bundled WASM', license: 'BSD-3-Clause AND Apache-2.0', source: 'bundled' });
rows.push({ name: 'Liberation fonts', version: readdirSync(join(root, 'assets/fonts/liberation')).filter((f) => f.endsWith('.ttf')).length + ' files', license: 'OFL-1.1', source: 'bundled' });
rows.push({ name: 'Handwriting fonts (Google Fonts)', version: readdirSync(join(root, 'assets/fonts/handwriting')).filter((f) => f.endsWith('.ttf')).length + ' files', license: 'OFL-1.1', source: 'bundled' });
rows.push({ name: 'Tesseract OCR engine and language data (tesseract.js, tessdata)', version: '7.x / 4.0.0_best_int, 4.1.0_fast', license: 'Apache-2.0', source: 'bundled' });
rows.push({ name: 'Lucide icons', version: 'inlined subset', license: 'ISC', source: 'bundled' });

const bad = rows.filter((r) => !ok(r.license));
rows.sort((a, b) => a.source.localeCompare(b.source) || a.name.localeCompare(b.name));
const md = ['# Third-party notices', '', 'Folio is licensed under GPL-3.0-or-later. It includes or links the following components.', 'Generated by `pnpm licenses`; do not edit by hand.', '', '| Component | Version | Licence | Source |', '| --- | --- | --- | --- |', ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.source} |`), ''].join('\n');
if (!process.argv.includes('--check')) writeFileSync(join(root, 'THIRD-PARTY-NOTICES.md'), md);
if (bad.length) {
  console.error(bad.map((r) => `licence needs review: ${r.name}@${r.version} (${r.license}, ${r.source})`).join('\n'));
  process.exit(1);
}
console.warn(`licenses: ${rows.length} components, all compatible with GPL-3.0-or-later`);
