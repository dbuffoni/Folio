// Embeds packages/db/src/migrations/*.sql into migrations.generated.ts. `--check` fails when out of date.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../packages/db/src/migrations/', import.meta.url));
const out = fileURLToPath(new URL('../packages/db/src/migrations.generated.ts', import.meta.url));
const items = readdirSync(dir)
  .filter((f) => /^\d{4}_.+\.sql$/.test(f))
  .sort()
  .map((f) => ({ version: Number(f.slice(0, 4)), name: f.replace(/\.sql$/, ''), sql: readFileSync(dir + f, 'utf8') }));
const text = `// GENERATED by tools/sync-migrations.ts — do not edit.\nimport type { Migration } from './migrations.ts';\n\nexport const EMBEDDED: Migration[] = ${JSON.stringify(items, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== text) {
    console.error('migrations.generated.ts is out of date: run `pnpm tsx tools/sync-migrations.ts`');
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
  console.log(`embedded ${items.length} migration(s)`);
}
